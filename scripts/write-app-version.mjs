import fs from "node:fs/promises"
import path from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const packagePath = path.join(rootDir, "package.json")
const outputPath = path.join(rootDir, "src", "generated", "app-version.ts")

const rawPackage = await fs.readFile(packagePath, "utf-8")
const packageJson = JSON.parse(rawPackage)

if (!packageJson || typeof packageJson.version !== "string" || packageJson.version.trim() === "") {
  throw new Error("package.json version is missing")
}

// La versione dell'app si aggiorna da sola: major.minor vengono dal
// package.json, la patch è il numero di commit su HEAD. Ogni nuovo
// commit (fix o feature) produce quindi una versione nuova senza bump
// manuali. Se git non è disponibile (es. build Docker senza .git),
// si ricade sulla versione base del package.json.
const baseVersion = packageJson.version.trim()
const [major, minor] = baseVersion.split(".")
let version = baseVersion
try {
  const commitCount = execFileSync("git", ["rev-list", "--count", "HEAD"], {
    cwd: rootDir,
    encoding: "utf-8",
  }).trim()
  if (/^\d+$/.test(commitCount)) {
    version = `${major}.${minor}.${commitCount}`
  }
} catch {}

const output = [
  "// AUTO-GENERATED by scripts/write-app-version.mjs — do not edit manually.",
  "// Versione automatica: <major>.<minor> dal package.json, patch = numero di",
  "// commit su HEAD. Cambia a ogni nuovo commit; fallback alla versione base",
  "// del package.json quando git non è disponibile.",
  `export const APP_VERSION = ${JSON.stringify(version)}`,
  "",
].join("\n")

await fs.mkdir(path.dirname(outputPath), { recursive: true })
await fs.writeFile(outputPath, output)
